package com.resume.aiops.report;

import com.lowagie.text.Document;
import com.lowagie.text.Element;
import com.lowagie.text.Font;
import com.lowagie.text.FontFactory;
import com.lowagie.text.PageSize;
import com.lowagie.text.Paragraph;
import com.lowagie.text.Phrase;
import com.lowagie.text.Rectangle;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import com.resume.aiops.agent.domain.DiagnosisTask;
import com.resume.aiops.config.AiOpsProperties;
import com.resume.aiops.memory.domain.ToolCallRecord;
import com.resume.aiops.rag.RunbookEvidence;
import java.io.IOException;
import java.io.OutputStream;
import java.awt.Color;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Instant;
import java.util.List;
import java.util.NoSuchElementException;
import org.springframework.core.io.Resource;
import org.springframework.core.io.UrlResource;
import org.springframework.stereotype.Service;

@Service
public class PdfReportService {
    private static final Color NAVY = new Color(15, 23, 42);
    private static final Color PURPLE = new Color(109, 84, 217);
    private static final Color GREEN = new Color(5, 150, 105);
    private static final Color LIGHT = new Color(241, 245, 249);
    private static final Color BORDER = new Color(203, 213, 225);
    private static final Color MUTED = new Color(71, 85, 105);
    private static final Font TITLE = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 22, Color.WHITE);
    private static final Font SUBTITLE = FontFactory.getFont(FontFactory.HELVETICA, 9, new Color(203, 213, 225));
    private static final Font HEADING = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 12, NAVY);
    private static final Font LABEL = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 8, MUTED);
    private static final Font BODY = FontFactory.getFont(FontFactory.HELVETICA, 9, NAVY);
    private static final Font SMALL = FontFactory.getFont(FontFactory.HELVETICA, 7, MUTED);
    private final AiOpsProperties properties;

    public PdfReportService(AiOpsProperties properties) {
        this.properties = properties;
    }

    public String generate(DiagnosisTask task, List<ToolCallRecord> calls,
                           List<RunbookEvidence> evidence, String conclusion) {
        String reportId = "report-" + task.taskId();
        try {
            Files.createDirectories(properties.reportsDirectory());
            Path target = properties.reportsDirectory().resolve(reportId + ".pdf").normalize();
            try (OutputStream output = Files.newOutputStream(target)) {
                Document document = new Document(PageSize.A4, 42, 42, 38, 38);
                PdfWriter writer = PdfWriter.getInstance(document, output);
                writer.setPdfVersion(PdfWriter.VERSION_1_5);
                document.addTitle("AIOps diagnosis report - " + task.alert().service());
                document.addSubject("Evidence-bound incident diagnosis");
                document.addAuthor("AIOps Agent Platform");
                document.open();
                document.add(header(task));
                document.add(spacer(12));
                document.add(summary(task, calls, evidence));
                document.add(spacer(14));
                document.add(sectionTitle("EXECUTIVE DIAGNOSIS"));
                document.add(conclusionBox(conclusion));
                document.add(spacer(14));
                document.add(sectionTitle("TOOL CALL EVIDENCE"));
                document.add(toolHeader());
                for (ToolCallRecord call : calls) {
                    document.add(toolRow(call));
                }
                document.add(spacer(14));
                document.add(sectionTitle("RUNBOOK REFERENCES"));
                int rank = 1;
                for (RunbookEvidence item : evidence) {
                    document.add(runbookRow(rank++, item));
                }
                document.add(spacer(15));
                Paragraph footer = new Paragraph(
                        "Generated by AIOps Agent Platform  |  " + Instant.now() +
                                "  |  Evidence is captured from read-only diagnostic tools.", SMALL);
                footer.setAlignment(Element.ALIGN_CENTER);
                document.add(footer);
                document.close();
            }
            return reportId;
        } catch (Exception exception) {
            throw new IllegalStateException("Cannot generate PDF report", exception);
        }
    }

    private PdfPTable header(DiagnosisTask task) {
        PdfPTable table = new PdfPTable(new float[]{4.5f, 1.2f});
        table.setWidthPercentage(100);
        PdfPCell title = new PdfPCell();
        title.setBorder(Rectangle.NO_BORDER);
        title.setBackgroundColor(NAVY);
        title.setPadding(18);
        title.addElement(new Paragraph("AIOps Diagnosis Report", TITLE));
        title.addElement(new Paragraph("EVIDENCE-BOUND INCIDENT ANALYSIS  /  " + task.taskId(), SUBTITLE));
        table.addCell(title);

        PdfPCell severity = new PdfPCell();
        severity.setBorder(Rectangle.NO_BORDER);
        severity.setBackgroundColor(PURPLE);
        severity.setPadding(14);
        Paragraph label = new Paragraph("SEVERITY", SUBTITLE);
        label.setAlignment(Element.ALIGN_CENTER);
        severity.addElement(label);
        Paragraph value = new Paragraph(task.alert().severity(), TITLE);
        value.setAlignment(Element.ALIGN_CENTER);
        severity.addElement(value);
        table.addCell(severity);
        return table;
    }

    private PdfPTable summary(DiagnosisTask task, List<ToolCallRecord> calls,
                              List<RunbookEvidence> evidence) {
        PdfPTable table = new PdfPTable(4);
        table.setWidthPercentage(100);
        addSummaryCell(table, "SERVICE", task.alert().service());
        addSummaryCell(table, "STATUS", "REPORT READY");
        addSummaryCell(table, "TOOL CALLS", String.valueOf(calls.size()));
        addSummaryCell(table, "RUNBOOK HITS", String.valueOf(evidence.size()));
        return table;
    }

    private void addSummaryCell(PdfPTable table, String label, String value) {
        PdfPCell cell = new PdfPCell();
        cell.setBorderColor(BORDER);
        cell.setBackgroundColor(LIGHT);
        cell.setPadding(10);
        cell.addElement(new Paragraph(label, LABEL));
        cell.addElement(new Paragraph(value, HEADING));
        table.addCell(cell);
    }

    private Paragraph sectionTitle(String value) {
        Paragraph paragraph = new Paragraph(value, HEADING);
        paragraph.setSpacingAfter(7);
        return paragraph;
    }

    private PdfPTable conclusionBox(String conclusion) {
        PdfPTable table = new PdfPTable(1);
        table.setWidthPercentage(100);
        PdfPCell cell = new PdfPCell(new Phrase(conclusion, BODY));
        cell.setPadding(13);
        cell.setBackgroundColor(new Color(245, 243, 255));
        cell.setBorderColor(new Color(196, 181, 253));
        table.addCell(cell);
        return table;
    }

    private PdfPTable toolHeader() {
        PdfPTable table = toolTable();
        addTableHeader(table, "SKILL");
        addTableHeader(table, "ARGUMENTS");
        addTableHeader(table, "RESULT");
        addTableHeader(table, "STATUS");
        addTableHeader(table, "LATENCY");
        return table;
    }

    private PdfPTable toolRow(ToolCallRecord call) {
        PdfPTable table = toolTable();
        addTableCell(table, call.skillName());
        addTableCell(table, call.arguments().toString());
        addTableCell(table, call.result().toString());
        PdfPCell status = cell(call.success() ? "SUCCESS" : "FAILED");
        status.setPhrase(new Phrase(call.success() ? "SUCCESS" : "FAILED",
                FontFactory.getFont(FontFactory.HELVETICA_BOLD, 8,
                        call.success() ? GREEN : Color.RED)));
        table.addCell(status);
        addTableCell(table, call.latencyMs() + " ms");
        return table;
    }

    private PdfPTable toolTable() {
        PdfPTable table = new PdfPTable(new float[]{1.6f, 1.4f, 2.9f, 1.0f, 0.9f});
        table.setWidthPercentage(100);
        table.setKeepTogether(true);
        return table;
    }

    private void addTableHeader(PdfPTable table, String value) {
        PdfPCell cell = new PdfPCell(new Phrase(value, FontFactory.getFont(
                FontFactory.HELVETICA_BOLD, 7, Color.WHITE)));
        cell.setPadding(7);
        cell.setBorderColor(NAVY);
        cell.setBackgroundColor(NAVY);
        table.addCell(cell);
    }

    private void addTableCell(PdfPTable table, String value) {
        table.addCell(cell(value));
    }

    private PdfPCell cell(String value) {
        PdfPCell cell = new PdfPCell(new Phrase(value, SMALL));
        cell.setPadding(7);
        cell.setBorderColor(BORDER);
        return cell;
    }

    private PdfPTable runbookRow(int rank, RunbookEvidence evidence) {
        PdfPTable table = new PdfPTable(new float[]{0.35f, 3f, 1.3f, 0.6f});
        table.setWidthPercentage(100);
        addTableCell(table, String.valueOf(rank));
        addTableCell(table, evidence.title());
        addTableCell(table, evidence.documentId());
        addTableCell(table, String.format("%.2f", evidence.score()));
        return table;
    }

    private Paragraph spacer(float height) {
        Paragraph paragraph = new Paragraph(" ");
        paragraph.setLeading(height);
        return paragraph;
    }

    public Resource load(String reportId) {
        try {
            Path base = properties.reportsDirectory().toAbsolutePath().normalize();
            Path report = base.resolve(reportId + ".pdf").normalize();
            if (!report.startsWith(base) || !Files.exists(report)) {
                throw new NoSuchElementException("Report not found: " + reportId);
            }
            return new UrlResource(report.toUri());
        } catch (IOException exception) {
            throw new IllegalStateException("Cannot load report", exception);
        }
    }
}
